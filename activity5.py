#operators 
#Arithmetic Operator
# + - Addition
# - - Subtraction
# / - Division 
# //  - Floor Division
# ** - Exponentiation 
# % - Modulus

a = 7
b = 3
c = 2

sum = a + b
difference = a - c
product = a * c
quotient = a / c
floorquotient = b // c
power = a ** c
remainder = a % b

print("The sum of ",a," and",b, "is ",sum)
print("The difference of ",a," and",c, "is ", difference)
print("The product of ",a," and",c, "is ", product)
print("The quotient of ",a," and",c, "is ", quotient)
print("The floor quotient of ",b," and",c, "is ", floorquotient)
print("The power of ",a," and",c, "is ", power)
print("The remainder of ",a," and",b, "is ", remainder)
